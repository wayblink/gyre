test('buildPlanSummary aggregates plan rows into totals', () => {
  const result = buildPlanSummary([
    {
      plan_name: 'GYRE 2023 Omnibus Incentive Plan',
      grant_count: '2',
      granted: '300',
      exercised: '20',
      cancelled: '5',
      outstanding: '275',
    },
    {
      plan_name: 'GYRE 2025 BC Subplan',
      grant_count: 1,
      granted: 100,
      exercised: 0,
      cancelled: 10,
      outstanding: 90,
    },
  ]);

  assert.equal(result.items.length, 2);
  assert.deepEqual(result.totals, {
    planCount: 2,
    grantCount: 3,
    granted: 400,
    exercised: 20,
    cancelled: 15,
    outstanding: 365,
  });
});

